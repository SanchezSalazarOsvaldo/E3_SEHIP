-- ---------------------------------------------------------------------
-- USUARIOS Y ROLES
-- ---------------------------------------------------------------------
CREATE TABLE rol (
    id_rol  SMALLINT    GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre  VARCHAR(30) NOT NULL,
    CONSTRAINT uq_rol_nombre UNIQUE (nombre)
);

CREATE TABLE usuario (
    id_usuario               INTEGER      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre                   VARCHAR(100) NOT NULL,                -- 1 a 100 caracteres (RF-ADM-04)
    correo                   VARCHAR(50)  NOT NULL,                -- 5 a 50 caracteres (RF-WEB-01, RF-ADM-04)
    contrasena_hash          VARCHAR(255) NOT NULL,                -- contraseña cifrada con bcrypt
    id_rol                   SMALLINT     NOT NULL,
    activo                   BOOLEAN      NOT NULL DEFAULT TRUE,   -- FALSE = cuenta inactiva (RF-ADM-07)
    protegido                BOOLEAN      NOT NULL DEFAULT FALSE,  -- TRUE = administrador inicial
    debe_cambiar_contrasena  BOOLEAN      NOT NULL DEFAULT FALSE,  -- TRUE = contraseña temporal sin cambiar
    codigo_recuperacion_hash VARCHAR(255) NULL,                    -- código de 6 dígitos cifrado con bcrypt
    codigo_expira            TIMESTAMP(0) NULL,                    -- vencimiento del código (15 minutos)
    intentos_codigo          SMALLINT     NOT NULL DEFAULT 0,      -- intentos fallidos con el código vigente
    fecha_creacion           TIMESTAMP(0) NOT NULL DEFAULT LOCALTIMESTAMP(0),
    CONSTRAINT fk_usuario_rol FOREIGN KEY (id_rol) REFERENCES rol (id_rol),
    CONSTRAINT ck_usuario_nombre CHECK (CHAR_LENGTH(nombre) BETWEEN 1 AND 100),
    CONSTRAINT ck_usuario_correo CHECK (CHAR_LENGTH(correo) BETWEEN 5 AND 50),
    CONSTRAINT ck_usuario_intentos CHECK (intentos_codigo BETWEEN 0 AND 5)
);
-- El correo es único sin distinguir mayúsculas y minúsculas.
CREATE UNIQUE INDEX uq_usuario_correo ON usuario (LOWER(correo));
CREATE INDEX idx_usuario_nombre ON usuario (nombre);
CREATE INDEX idx_usuario_rol ON usuario (id_rol);

-- ---------------------------------------------------------------------
-- CATÁLOGO GEOGRÁFICO
-- ---------------------------------------------------------------------
CREATE TABLE alcaldia (
    id_alcaldia           SMALLINT    GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre                VARCHAR(60) NOT NULL,
    porcentaje_absorcion  SMALLINT    NULL,   -- % estimado de absorción del suelo, entero de 0 a 100 (RF-MOV-04)
    CONSTRAINT uq_alcaldia_nombre UNIQUE (nombre),
    CONSTRAINT ck_alcaldia_absorcion CHECK (porcentaje_absorcion IS NULL OR porcentaje_absorcion BETWEEN 0 AND 100)
);

CREATE TABLE punto_critico (
    id_punto        INTEGER      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_alcaldia     SMALLINT     NOT NULL,
    latitud         NUMERIC(9,6) NOT NULL,           -- coordenadas decimales con seis decimales
    longitud        NUMERIC(9,6) NOT NULL,
    fecha_registro  TIMESTAMP(0) NOT NULL DEFAULT LOCALTIMESTAMP(0),
    CONSTRAINT fk_punto_alcaldia FOREIGN KEY (id_alcaldia) REFERENCES alcaldia (id_alcaldia),
    CONSTRAINT ck_punto_latitud  CHECK (latitud  BETWEEN -90  AND 90),
    CONSTRAINT ck_punto_longitud CHECK (longitud BETWEEN -180 AND 180)
);
-- RF-MOV-05: hasta 100 puntos por alcaldía, del registro más reciente al más antiguo.
CREATE INDEX idx_punto_alcaldia_fecha ON punto_critico (id_alcaldia, fecha_registro DESC);

-- ---------------------------------------------------------------------
-- TABLA MAESTRA NORMATIVA (RF-ADM-03)
-- El valor se sobrescribe sin conservar el anterior; fecha_actualizacion
-- registra desde cuándo rige el valor vigente (la escribe la aplicación).
-- ---------------------------------------------------------------------
CREATE TABLE coeficiente_normativo (
    tipo                 VARCHAR(2)   PRIMARY KEY,   -- Cp: superficie permeable, Ci: impermeable
    valor                NUMERIC(3,2) NULL,          -- 0.05 a 0.95; NULL = pendiente de capturar
    fecha_actualizacion  TIMESTAMP(0) NOT NULL DEFAULT LOCALTIMESTAMP(0),
    CONSTRAINT ck_coeficiente_tipo  CHECK (tipo IN ('Cp', 'Ci')),
    CONSTRAINT ck_coeficiente_valor CHECK (valor IS NULL OR valor BETWEEN 0.05 AND 0.95)
);

CREATE TABLE intensidad_lluvia (
    id_alcaldia          SMALLINT     NOT NULL,
    periodo_retorno      SMALLINT     NOT NULL,      -- años: 2, 5, 10, 20 o 50
    intensidad_mm_h      NUMERIC(5,2) NULL,          -- 10.00 a 250.00; NULL = pendiente de capturar
    fecha_actualizacion  TIMESTAMP(0) NOT NULL DEFAULT LOCALTIMESTAMP(0),
    PRIMARY KEY (id_alcaldia, periodo_retorno),
    CONSTRAINT fk_intensidad_alcaldia FOREIGN KEY (id_alcaldia) REFERENCES alcaldia (id_alcaldia),
    CONSTRAINT ck_intensidad_periodo CHECK (periodo_retorno IN (2, 5, 10, 20, 50)),
    CONSTRAINT ck_intensidad_valor   CHECK (intensidad_mm_h IS NULL OR intensidad_mm_h BETWEEN 10.00 AND 250.00)
);

-- ---------------------------------------------------------------------
-- PROYECTOS Y SIMULACIONES (módulo web de simulación hidrológica)
-- Los cálculos de RF-WEB-04, 05 y 06 se guardan en el propio proyecto;
-- un dato sin calcular queda en NULL y la aplicación muestra "Sin calcular".
-- ---------------------------------------------------------------------
CREATE TABLE proyecto (
    id_proyecto            INTEGER       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,   -- entero único >= 1
    id_usuario             INTEGER       NOT NULL,                  -- autor (usuario de la sesión)
    nombre                 VARCHAR(100)  NOT NULL,                  -- 1 a 100 caracteres; admite repetidos
    id_alcaldia            SMALLINT      NOT NULL,
    latitud                NUMERIC(9,6)  NOT NULL,                  -- punto de ubicación en el mapa
    longitud               NUMERIC(9,6)  NOT NULL,
    fecha_creacion         DATE          NOT NULL DEFAULT CURRENT_DATE,   -- YYYY-MM-DD
    estado                 VARCHAR(10)   NOT NULL DEFAULT 'En proceso',
    superficie_permeable   NUMERIC(9,2)  NULL,                      -- m², 0.00 a 1,000,000.00 (RF-WEB-04)
    superficie_impermeable NUMERIC(9,2)  NULL,                      -- m², 0.00 a 1,000,000.00
    superficie_total       NUMERIC(9,2)  NULL,                      -- m², 0.01 a 1,000,000.00
    coeficiente_c          NUMERIC(3,2)  NULL,                      -- 0.05 a 0.95 (RF-WEB-04)
    intensidad_mm_h        NUMERIC(5,2)  NULL,                      -- 10.00 a 250.00 (RF-WEB-05)
    periodo_retorno        SMALLINT      NULL,                      -- 2, 5, 10, 20 o 50 años
    caudal_pico            NUMERIC(12,3) NULL,                      -- m3/s, tres decimales (RF-WEB-06)
    CONSTRAINT fk_proyecto_usuario  FOREIGN KEY (id_usuario)  REFERENCES usuario (id_usuario),
    CONSTRAINT fk_proyecto_alcaldia FOREIGN KEY (id_alcaldia) REFERENCES alcaldia (id_alcaldia),
    CONSTRAINT ck_proyecto_nombre CHECK (CHAR_LENGTH(nombre) BETWEEN 1 AND 100),
    CONSTRAINT ck_proyecto_estado_valor CHECK (estado IN ('En proceso', 'Calculado')),
    CONSTRAINT ck_proyecto_latitud  CHECK (latitud  BETWEEN -90  AND 90),
    CONSTRAINT ck_proyecto_longitud CHECK (longitud BETWEEN -180 AND 180),
    CONSTRAINT ck_proyecto_superficies CHECK (
        (superficie_permeable   IS NULL OR superficie_permeable   BETWEEN 0 AND 1000000)
        AND (superficie_impermeable IS NULL OR superficie_impermeable BETWEEN 0 AND 1000000)
        AND (superficie_total       IS NULL OR superficie_total       BETWEEN 0.01 AND 1000000)),
    CONSTRAINT ck_proyecto_total CHECK (
        superficie_total IS NULL
        OR (superficie_permeable IS NOT NULL AND superficie_impermeable IS NOT NULL
            AND superficie_permeable + superficie_impermeable = superficie_total)),
    CONSTRAINT ck_proyecto_coeficiente CHECK (coeficiente_c IS NULL OR coeficiente_c BETWEEN 0.05 AND 0.95),
    CONSTRAINT ck_proyecto_intensidad  CHECK (intensidad_mm_h IS NULL OR intensidad_mm_h BETWEEN 10.00 AND 250.00),
    CONSTRAINT ck_proyecto_periodo     CHECK (periodo_retorno IS NULL OR periodo_retorno IN (2, 5, 10, 20, 50)),
    CONSTRAINT ck_proyecto_intensidad_periodo CHECK ((intensidad_mm_h IS NULL) = (periodo_retorno IS NULL)),
    CONSTRAINT ck_proyecto_caudal CHECK (caudal_pico IS NULL OR caudal_pico >= 0),
    CONSTRAINT ck_proyecto_estado CHECK (estado = 'En proceso' OR caudal_pico IS NOT NULL)
);
-- RF-WEB-03: historial paginado por usuario, fecha de creación descendente.
CREATE INDEX idx_proyecto_historial ON proyecto (id_usuario, fecha_creacion DESC, id_proyecto DESC);
CREATE INDEX idx_proyecto_alcaldia ON proyecto (id_alcaldia);

CREATE TABLE simulacion_mitigacion (
    id_simulacion            INTEGER       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_proyecto              INTEGER       NOT NULL,
    tipo_obra                VARCHAR(30)   NOT NULL,
    capacidad_almacenamiento NUMERIC(7,2)  NOT NULL,   -- m3, 0.01 a 50,000.00 (RF-WEB-07)
    caudal_pico              NUMERIC(12,3) NOT NULL,   -- caudal pico del proyecto al simular (vigencia)
    latitud                  NUMERIC(9,6)  NOT NULL,   -- ubicación de la obra dentro de la zona afectada
    longitud                 NUMERIC(9,6)  NOT NULL,
    distancia_m              NUMERIC(9,2)  NOT NULL,   -- distancia al punto del proyecto (m)
    eficiencia               NUMERIC(4,3)  NOT NULL,   -- 0.500 (borde de la zona) a 1.000 (junto al proyecto)
    retencion                NUMERIC(12,6) NOT NULL,   -- R = capacidad / 3,600 x eficiencia (m3/s)
    caudal_ajustado          NUMERIC(12,3) NOT NULL,   -- Qmitigado = Qpico - R, mínimo 0.000 (m3/s)
    caudal_permitido         NUMERIC(12,3) NOT NULL,   -- Qpermitido = Cp x I x A / 360 (m3/s)
    dentro_de_capacidad      BOOLEAN       NOT NULL,   -- TRUE si Qmitigado <= Qpermitido
    fecha_hora               TIMESTAMP(0)  NOT NULL DEFAULT LOCALTIMESTAMP(0),
    CONSTRAINT fk_simulacion_proyecto FOREIGN KEY (id_proyecto) REFERENCES proyecto (id_proyecto),
    CONSTRAINT ck_simulacion_tipo CHECK (tipo_obra IN ('Pozo de Infiltración', 'Tanque de Tormenta', 'Jardín de Lluvia')),
    CONSTRAINT ck_simulacion_capacidad CHECK (capacidad_almacenamiento BETWEEN 0.01 AND 50000.00),
    CONSTRAINT ck_simulacion_retencion CHECK (retencion >= 0),
    CONSTRAINT ck_simulacion_eficiencia CHECK (eficiencia BETWEEN 0.5 AND 1),
    CONSTRAINT ck_simulacion_ajustado  CHECK (caudal_ajustado >= 0),
    CONSTRAINT ck_simulacion_permitido CHECK (caudal_permitido >= 0)
);
CREATE INDEX idx_simulacion_proyecto_fecha ON simulacion_mitigacion (id_proyecto, fecha_hora DESC);

CREATE TABLE reporte_pdf (
    id_reporte        INTEGER       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_proyecto       INTEGER       NOT NULL,
    nombre_archivo    VARCHAR(150)  NOT NULL,
    contenido         BYTEA         NOT NULL,   -- archivo PDF completo (el servidor en la nube no conserva archivos)
    tamano_bytes      INTEGER       NOT NULL,
    fecha_generacion  TIMESTAMP(0)  NOT NULL DEFAULT LOCALTIMESTAMP(0),   -- fecha de emisión del reporte
    CONSTRAINT fk_reporte_proyecto FOREIGN KEY (id_proyecto) REFERENCES proyecto (id_proyecto),
    CONSTRAINT ck_reporte_tamano CHECK (tamano_bytes BETWEEN 1 AND 10485760)   -- máximo 10 MB (RF-WEB-08)
);
CREATE INDEX idx_reporte_proyecto_fecha ON reporte_pdf (id_proyecto, fecha_generacion DESC);

-- ---------------------------------------------------------------------
-- SESIONES DEL SERVIDOR WEB
-- Cada fila es una sesión abierta (cookie del navegador). Guardarlas en la base permite que la
-- sesión sobreviva a reinicios del servidor y que varios servidores compartan las mismas sesiones.
-- ---------------------------------------------------------------------
CREATE TABLE sesion (
    sid     VARCHAR(255) PRIMARY KEY,
    datos   JSON         NOT NULL,
    expira  TIMESTAMPTZ  NOT NULL
);
CREATE INDEX idx_sesion_expira ON sesion (expira);

-- ---------------------------------------------------------------------
-- ADMINISTRADOR INICIAL PROTEGIDO
-- Debe existir siempre un administrador que cree las demás cuentas. El
-- administrador inicial (protegido = TRUE) no se puede eliminar, deshabilitar,
-- degradar de rol ni duplicar; sí se pueden modificar su nombre, correo y
-- contraseña. Las reglas viven en la base de datos para que ningún módulo
-- (ni un error de programación) pueda saltárselas.
-- ---------------------------------------------------------------------
CREATE FUNCTION fn_proteger_administrador_inicial() RETURNS TRIGGER
LANGUAGE plpgsql AS $$
BEGIN
    IF TG_OP = 'INSERT' THEN
        IF NEW.protegido THEN
            IF EXISTS (SELECT 1 FROM usuario WHERE protegido) THEN
                RAISE EXCEPTION 'Ya existe un administrador inicial protegido.';
            END IF;
            IF NOT NEW.activo THEN
                RAISE EXCEPTION 'El administrador inicial debe crearse activo.';
            END IF;
        END IF;
        RETURN NEW;
    END IF;

    IF TG_OP = 'UPDATE' THEN
        IF OLD.protegido THEN
            IF NOT NEW.activo THEN
                RAISE EXCEPTION 'El administrador inicial no puede deshabilitarse.';
            END IF;
            IF NEW.id_rol <> OLD.id_rol THEN
                RAISE EXCEPTION 'El administrador inicial no puede cambiar de rol.';
            END IF;
            IF NOT NEW.protegido THEN
                RAISE EXCEPTION 'No se puede quitar la protección al administrador inicial.';
            END IF;
        ELSIF NEW.protegido THEN
            RAISE EXCEPTION 'La protección solo se asigna al crear el administrador inicial.';
        END IF;
        RETURN NEW;
    END IF;

    -- DELETE
    IF OLD.protegido THEN
        RAISE EXCEPTION 'El administrador inicial no puede eliminarse.';
    END IF;
    RETURN OLD;
END;
$$;

CREATE TRIGGER trg_usuario_antes_insertar BEFORE INSERT ON usuario
    FOR EACH ROW EXECUTE FUNCTION fn_proteger_administrador_inicial();
CREATE TRIGGER trg_usuario_antes_actualizar BEFORE UPDATE ON usuario
    FOR EACH ROW EXECUTE FUNCTION fn_proteger_administrador_inicial();
CREATE TRIGGER trg_usuario_antes_eliminar BEFORE DELETE ON usuario
    FOR EACH ROW EXECUTE FUNCTION fn_proteger_administrador_inicial();

